  static const double defaultBorderRadius = 8.0;

  /// General default padding value used throughout the application.
  static const double defaultPadding = 16.0;

  /// Default size for icons.
  static const double defaultIconSize = 24.0;

  /// Default vertical spacing between a label and its associated input field.
  static const double defaultLabelBottomPadding = 8.0;

  /// Default horizontal and vertical content padding for text fields.
  static const double defaultTextFieldContentPadding = 12.0;
}
